// AG Grid (v33+ Theming API): a Quartz theme whose parameters are our CSS variables. AG Grid accepts
// var() in colour, length and font parameters, so the grid follows the project's dark theme with no
// second theme. Parameter names checked against ag-grid-community / ag-stack 36.3 type definitions.
import { tokenRef } from "./tokens.mjs";

const PARAMS = [
  ["accentColor", "color", "primary"],
  ["backgroundColor", "color", "background"],
  ["foregroundColor", "color", "foreground"],
  ["borderColor", "color", "border"],
  ["chromeBackgroundColor", "color", "muted"],
  ["headerBackgroundColor", "color", "muted"],
  ["headerTextColor", "color", "muted-foreground"],
  ["rowHoverColor", "color", "accent"],
  ["selectedRowBackgroundColor", "color", "accent"],
  ["fontFamily", "font", "sans"],
  ["fontSize", "text", "sm"],
  ["spacing", "space", "2"],
  ["borderRadius", "radius", "md"],
  ["wrapperBorderRadius", "radius", "lg"],
];

export function emitAgGrid(tokens) {
  const params = PARAMS.map(([param, group, name]) => `  ${param}: "${tokenRef(tokens, group, name, `the AG Grid theme (${param})`)}",`);
  params.push('  browserColorScheme: "inherit", // scrollbars and inputs follow the page\'s color-scheme');
  return `// generated by finally-good-ui emit-tokens.mjs (--format ag-grid); edit the tokens, not this file.
// Needs the variables from --format css (or tailwind4 / shadcn). Dark mode follows them: no second theme.
import { themeQuartz } from "ag-grid-community";

export const gridTheme = themeQuartz.withParams({
${params.join("\n")}
});
// <AgGridReact theme={gridTheme} … />  (Vue / Angular: the same theme prop or gridOptions.theme)
`;
}
