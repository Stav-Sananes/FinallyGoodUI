// SwiftUI from a token set: an asset catalog with one colour set per role (light + dark appearance, so
// the system switches them) and a Swift file of typed accessors: Palette, Space, Radius, TextStep (sized
// with Dynamic Type) and Motion (curves that respect Reduce Motion). Colours are sRGB.
import { flatten, groupTokens, parseDimension, parseDuration, parseEasing, textMetrics, fontLoad } from "./tokens.mjs";
import { parseColor } from "./contrast.mjs";

export const CATALOG = "DesignTokens.xcassets";
const FOLDER = "Tokens"; // a namespaced folder: Color("Tokens/Primary") never clashes with SwiftUI's Color.primary

const pascal = (name) => name.split(/[-_.]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
/** Swift identifier: "primary-foreground" -> primaryForeground, "4" -> s4, "1.5" -> s1_5. */
export const swiftName = (name) => {
  const id = name.replace(/\./g, "_").replace(/-(\w)/g, (_, c) => c.toUpperCase());
  return /^\d/.test(id) ? `s${id}` : id;
};
const cg = (n) => (Number.isInteger(n) ? `${n}` : `${Math.round(n * 1000) / 1000}`);
const json = (v) => JSON.stringify(v, null, 2) + "\n";
const INFO = { author: "xcode", version: 1 };

/** A colour set's "color" entry: sRGB components as the decimal strings Xcode writes. */
export function colorEntry(css) {
  const c = parseColor(css);
  if (!c) throw new Error(`cannot convert colour ${css} to sRGB`);
  const f = (x) => (Math.round(x * 1000) / 1000).toFixed(3);
  return { "color-space": "srgb", components: { red: f(c.r), green: f(c.g), blue: f(c.b), alpha: f(c.a) } };
}

function colorSet(row) {
  const colors = [{ idiom: "universal", color: colorEntry(row.light) }];
  colors.push({ appearances: [{ appearance: "luminosity", value: "dark" }], idiom: "universal", color: colorEntry(row.dark ?? row.light) });
  return { colors, info: INFO };
}

// Text step -> the Dynamic Type style it scales with.
const RELATIVE_TO = { xs: "caption2", sm: "footnote", base: "body", lg: "title3", xl: "title3", "2xl": "title2", "3xl": "title", "4xl": "largeTitle", "5xl": "largeTitle", "6xl": "largeTitle" };

function swiftFile(rows, tokens) {
  const colors = rows.filter((r) => r.group === "color");
  const dims = (group) => rows.filter((r) => r.group === group && parseDimension(r.light))
    .map((r) => `    public static let ${swiftName(r.name)}: CGFloat = ${cg(parseDimension(r.light).value)}`).join("\n");
  const steps = rows.filter((r) => r.group === "text").map((r) => {
    const size = parseDimension(r.light)?.value;
    const m = Object.fromEntries(textMetrics(r.token).map((x) => [x.suffix, x.value]));
    const lh = m["line-height"] != null ? Number(m["line-height"]) * size : size * 1.2;
    const ls = parseDimension(m["letter-spacing"] ?? "");
    const tracking = ls ? (ls.unit === "em" ? ls.value * size : ls.value) : 0;
    return `    public static let ${swiftName(r.name)} = TextStep(size: ${cg(size)}, lineHeight: ${cg(lh)}, tracking: ${cg(tracking)}, relativeTo: .${RELATIVE_TO[r.name] ?? "body"})`;
  });
  const font = rows.find((r) => r.group === "font" && r.name === "sans" && fontLoad(r.token));
  const family = font ? [].concat(font.token.$value)[0] : null;
  const fontExpr = family ? `.custom(${JSON.stringify(family)}, size: step.size * scale)` : ".system(size: step.size * scale)";
  const durations = [...groupTokens(tokens?.duration)].map(([n, t]) => [swiftName(n), parseDuration(t.$value)?.value]).filter(([, v]) => v != null);
  const curves = [...groupTokens(tokens?.easing)].map(([n, t]) => [swiftName(n), parseEasing(t.$value)]).filter(([, v]) => v);

  return `// generated by finally-good-ui emit-tokens.mjs (--format swiftui); edit the tokens, not this file.
// Add DesignTokens.xcassets and this file to the app target. Colours switch with the system appearance.
//   Text("Total").textStep(.lg).foregroundStyle(Palette.foreground)
//   .padding(Space.s4).background(Palette.card, in: .rect(cornerRadius: Radius.md))
//   withAnimation(Motion.animation(.move, Motion.standard, reduceMotion: reduceMotion)) { ... }
//     with @Environment(\\.accessibilityReduceMotion) private var reduceMotion
${family ? `// Font: add the "${family}" files to the target and list them under UIAppFonts (Info.plist).\n` : ""}import SwiftUI

/// Colour roles, light and dark, from ${CATALOG}.
public enum Palette {
${colors.map((r) => `    public static let ${swiftName(r.name)} = Color("${FOLDER}/${pascal(r.name)}", bundle: .main)`).join("\n")}
}

/// Spacing in points (the 4-based scale).
public enum Space {
${dims("space")}
}

/// Corner radii in points.
public enum Radius {
${dims("radius")}
}

/// A step of the type scale. Sizes scale with Dynamic Type relative to a system text style.
public struct TextStep: Sendable {
    public let size: CGFloat
    public let lineHeight: CGFloat
    public let tracking: CGFloat
    public let relativeTo: Font.TextStyle

${steps.join("\n")}
}

private struct TextStepModifier: ViewModifier {
    let step: TextStep
    @ScaledMetric private var scale: CGFloat

    init(_ step: TextStep) {
        self.step = step
        _scale = ScaledMetric(wrappedValue: 1, relativeTo: step.relativeTo)
    }

    func body(content: Content) -> some View {
        content
            .font(${fontExpr})
            .tracking(step.tracking * scale)
            .lineSpacing(max(0, (step.lineHeight - step.size * 1.2) * scale)) // SwiftUI adds this to the font's own line height
    }
}

public extension View {
    /// Font size, tracking and line spacing of a type-scale step, scaled with Dynamic Type.
    func textStep(_ step: TextStep) -> some View { modifier(TextStepModifier(step)) }
}

/// Durations (seconds) and easing curves.
public enum Motion {
${durations.map(([n, v]) => `    public static let ${n}: Double = ${cg(v / 1000)}`).join("\n")}

    public struct Curve: Sendable {
        public let x1: Double, y1: Double, x2: Double, y2: Double
${curves.map(([n, p]) => `        public static let ${n} = Curve(x1: ${p[0]}, y1: ${p[1]}, x2: ${p[2]}, y2: ${p[3]})`).join("\n")}
    }

    /// An animation on a token curve; nil (no animation) for movement when Reduce Motion is on.
    /// Pass reduceMotion: false for a fade, which may keep its duration.
    public static func animation(_ curve: Curve, _ duration: Double, reduceMotion: Bool) -> Animation? {
        reduceMotion ? nil : .timingCurve(curve.x1, curve.y1, curve.x2, curve.y2, duration: duration)
    }
}
`;
}

/** {relative path: content} for the asset catalog and DesignTokens.swift. */
export function swiftuiFiles(tokens) {
  const rows = flatten(tokens);
  const files = {
    [`${CATALOG}/Contents.json`]: json({ info: INFO }),
    [`${CATALOG}/${FOLDER}/Contents.json`]: json({ info: INFO, properties: { "provides-namespace": true } }),
  };
  for (const r of rows.filter((x) => x.group === "color")) files[`${CATALOG}/${FOLDER}/${pascal(r.name)}.colorset/Contents.json`] = json(colorSet(r));
  files["DesignTokens.swift"] = swiftFile(rows, tokens);
  return files;
}
