// Override CSS for libraries that hard-code their own motion, so they follow the project's motion
// tokens. Keyed by the stack profile's `interaction` names. Every selector starts with `:root` to
// out-rank the library's own rules whatever order the stylesheets load in; only timing is
// overridden, never what the library animates.
import { tokenRef, MissingTokenError } from "./tokens.mjs";

export { MissingTokenError };

const REDUCE = "@media (prefers-reduced-motion: reduce)";

const ADAPTERS = {
  sonner: {
    note: "also vue-sonner and svelte-sonner. Replaces 400ms transform/opacity/height and 200ms shadow; reduced motion is built in",
    uses: [["duration", "medium"], ["duration", "short"], ["easing", "move"]],
    css: (v) => `:root [data-sonner-toaster] [data-sonner-toast] {
  transition-duration: ${v.duration.medium}, ${v.duration.medium}, ${v.duration.medium}, ${v.duration.short};
  transition-timing-function: ${v.easing.move};
}`,
  },
  cmdk: {
    note: "the list glides to its new height as results filter; the palette itself opens instantly",
    uses: [["duration", "short"], ["easing", "move"]],
    css: (v) => `:root [cmdk-list] {
  height: var(--cmdk-list-height);
  transition: height ${v.duration.short} ${v.easing.move};
}
${REDUCE} { :root [cmdk-list] { transition: none; } }`,
  },
  "react-day-picker": {
    note: "with the animate prop: month slide; no reduced-motion handling of its own",
    uses: [["duration", "medium"], ["easing", "move"]],
    css: (v) => `:root .rdp-root {
  --rdp-animation_duration: ${v.duration.medium};
  --rdp-animation_timing: ${v.easing.move};
}
${REDUCE} { :root .rdp-root { --rdp-animation_duration: 0s; } }`,
  },
  "vaul-unmaintained": {
    note: "move to the primitive library's Drawer when you can. Replaces 0.5s; fades instead of sliding under reduced motion",
    uses: [["duration", "medium"], ["duration", "short"], ["easing", "snappy"], ["easing", "exit"]],
    css: (v) => `:root [data-vaul-drawer], :root [data-vaul-overlay] {
  transition-duration: ${v.duration.medium};
  transition-timing-function: ${v.easing.snappy};
  animation-duration: ${v.duration.medium};
  animation-timing-function: ${v.easing.snappy};
}
:root [data-vaul-drawer][data-state="closed"], :root [data-vaul-overlay][data-state="closed"] {
  animation-duration: ${v.duration.short};
  animation-timing-function: ${v.easing.exit};
}
${REDUCE} {
  :root [data-vaul-drawer][data-vaul-snap-points][data-vaul-drawer-direction][data-state="open"] { animation-name: fadeIn; }
  :root [data-vaul-drawer][data-vaul-snap-points][data-vaul-drawer-direction][data-state="closed"] { animation-name: fadeOut; }
}`,
  },
};

export const ADAPTER_LIBS = Object.keys(ADAPTERS);

/** var(--…) references for the tokens an adapter uses; throws when the token set lacks one. */
function references(tokens, uses, lib) {
  const refs = {};
  for (const [group, name] of uses) (refs[group] ||= {})[name] = tokenRef(tokens, group, name, `the ${lib} adapter`);
  return refs;
}

/** Adapter CSS for `libs` (stack-profile interaction names; others are skipped), all when omitted. */
export function emitAdapters(tokens, libs = ADAPTER_LIBS) {
  const chosen = libs.filter((lib) => ADAPTERS[lib]);
  const head = "/* generated by finally-good-ui emit-tokens.mjs (--format adapters); any load order: :root out-ranks the libraries' selectors.\n" +
    "   Needs the variables from --format css (or tailwind4 / shadcn). */\n";
  if (!chosen.length) return head + `/* no adapter needed for: ${libs.join(", ") || "(none)"} */\n`;
  return head + chosen.map((lib) => {
    const a = ADAPTERS[lib];
    return `\n/* ${lib}: ${a.note} */\n${a.css(references(tokens, a.uses, lib))}\n`;
  }).join("");
}
