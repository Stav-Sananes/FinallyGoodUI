// Jetpack Compose theme from a token set, in the files Material Theme Builder exports: Color.kt,
// Type.kt and Theme.kt (light/dark ColorScheme from our roles, our extended colours through a
// CompositionLocal, shapes from the radius scale), plus Tokens.kt (spacing, radius, motion).
// Colours are sRGB ARGB literals; sizes dp/sp; line-height and letter-spacing in sp for each step.
import { flatten, groupTokens, parseDimension, parseDuration, parseEasing, fontLoad } from "./tokens.mjs";
import { parseColor } from "./contrast.mjs";
import { materialColors, textStepMetrics, TEXT_ROLES } from "./material.mjs";

/** Compose Color literal: Color(0xAARRGGBB). */
export function kotlinColor(css) {
  const c = parseColor(css);
  if (!c) throw new Error(`cannot convert colour ${css} to sRGB`);
  const hex = (x) => Math.round(x * 255).toString(16).padStart(2, "0").toUpperCase();
  return `Color(0x${hex(c.a)}${hex(c.r)}${hex(c.g)}${hex(c.b)})`;
}

/** Kotlin identifier: "primary-foreground" -> primaryForeground, "4" -> s4, "1.5" -> s1_5. */
export const kotlinName = (name) => {
  const id = name.replace(/\./g, "_").replace(/-(\w)/g, (_, c) => c.toUpperCase());
  return /^\d/.test(id) ? `s${id}` : id;
};
const pascal = (name) => { const n = kotlinName(name); return n[0].toUpperCase() + n.slice(1); };
const num = (n) => `${Math.round(n * 1000) / 1000}`;
const float = (n) => `${num(n)}f`;
const header = (pkg) => `// generated by finally-good-ui emit-tokens.mjs (--format compose); edit the tokens, not this file.\npackage ${pkg}\n`;

function colorKt(pkg, rows) {
  const colors = rows.filter((r) => r.group === "color");
  const line = (r, theme, value) => `val ${pascal(r.name)}${theme} = ${kotlinColor(value)}`;
  return `${header(pkg)}
import androidx.compose.ui.graphics.Color

${colors.map((r) => line(r, "Light", r.light)).join("\n")}

${colors.map((r) => line(r, "Dark", r.dark ?? r.light)).join("\n")}
`;
}

function typeKt(pkg, rows) {
  const steps = textStepMetrics(rows);
  const font = rows.find((r) => r.group === "font" && r.name === "sans" && fontLoad(r.token));
  const family = font ? [].concat(font.token.$value)[0] : null;
  const style = (m) => [
    ...(family ? ["fontFamily = AppFontFamily"] : []),
    `fontSize = ${num(m.size)}.sp`,
    ...(m.lineHeight != null ? [`lineHeight = ${num(m.lineHeight)}.sp`] : []),
    `letterSpacing = ${num(m.letterSpacing)}.sp`,
  ].join(", ");
  const roles = TEXT_ROLES.filter(([, step]) => steps.has(step));
  return `${header(pkg)}
import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
${family ? "import androidx.compose.ui.text.font.FontFamily\n" : ""}import androidx.compose.ui.unit.sp
${family ? `
// "${family}": add its files under res/font and list them here, e.g. Font(R.font.${kotlinName(family.toLowerCase().replace(/\s+/g, "_"))}_regular).
// Until then the platform font is used.
val AppFontFamily: FontFamily = FontFamily.Default
` : ""}
val AppTypography = Typography(
${roles.map(([role, step]) => `    ${role} = TextStyle(${style(steps.get(step))}),`).join("\n")}
)
`;
}

function themeKt(pkg, rows) {
  const { slots, extended } = materialColors(rows);
  // Compose still reads background/onBackground (Scaffold's container); Flutter dropped them.
  const composeSlots = [...slots, ...slots.filter(([s]) => s === "surface" || s === "onSurface")
    .map(([s, r]) => [s === "surface" ? "background" : "onBackground", r])];
  const scheme = (theme) => composeSlots.map(([slot, r]) => `    ${slot} = ${pascal(r.name)}${theme},`).join("\n");
  const fields = extended.map((r) => kotlinName(r.name));
  const ext = (theme) => extended.map((r) => `    ${kotlinName(r.name)} = ${pascal(r.name)}${theme},`).join("\n");
  const radius = (name, fallback) => {
    const r = rows.find((x) => x.group === "radius" && x.name === name);
    return r ? `${num(parseDimension(r.light).value)}.dp` : fallback;
  };
  return `${header(pkg)}
import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Shapes
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.runtime.Immutable
import androidx.compose.runtime.ReadOnlyComposable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

// Surface tint is transparent so Material doesn't wash surfaces in primary. No dynamic colour
// (Android 12 wallpaper colours): the brand palette is the design.
private val LightColors = lightColorScheme(
${scheme("Light")}
    surfaceTint = Color.Transparent,
)

private val DarkColors = darkColorScheme(
${scheme("Dark")}
    surfaceTint = Color.Transparent,
)

/** Colours Material's ColorScheme has no slot for. Read with AppTheme.extendedColors. */
@Immutable
data class ExtendedColors(
${fields.map((f) => `    val ${f}: Color,`).join("\n")}
)

private val LightExtended = ExtendedColors(
${ext("Light")}
)

private val DarkExtended = ExtendedColors(
${ext("Dark")}
)

val LocalExtendedColors = staticCompositionLocalOf { LightExtended }

val AppShapes = Shapes(
    extraSmall = RoundedCornerShape(${radius("sm", "4.dp")}),
    small = RoundedCornerShape(${radius("sm", "4.dp")}),
    medium = RoundedCornerShape(${radius("md", "8.dp")}),
    large = RoundedCornerShape(${radius("lg", "12.dp")}),
    extraLarge = RoundedCornerShape(${radius("xl", "16.dp")}),
)

/** Wrap the app: AppTheme { ... }. Follows the system dark setting unless darkTheme is passed. */
@Composable
fun AppTheme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
    CompositionLocalProvider(LocalExtendedColors provides if (darkTheme) DarkExtended else LightExtended) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColors else LightColors,
            typography = AppTypography,
            shapes = AppShapes,
            content = content,
        )
    }
}

object AppTheme {
    val extendedColors: ExtendedColors
        @Composable @ReadOnlyComposable get() = LocalExtendedColors.current
}
`;
}

function tokensKt(pkg, rows, tokens) {
  const dims = (group) => rows.filter((r) => r.group === group && parseDimension(r.light))
    .map((r) => `    val ${kotlinName(r.name)} = ${num(parseDimension(r.light).value)}.dp`).join("\n");
  const durations = [...groupTokens(tokens?.duration)].map(([n, t]) => [kotlinName(n), parseDuration(t.$value)?.value]).filter(([, v]) => v != null);
  const curves = [...groupTokens(tokens?.easing)].map(([n, t]) => [kotlinName(n), parseEasing(t.$value)]).filter(([, v]) => v);
  return `${header(pkg)}
import android.provider.Settings
import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.animation.core.Easing
import androidx.compose.animation.core.FiniteAnimationSpec
import androidx.compose.animation.core.tween
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp

/** Spacing (the 4-based scale): Modifier.padding(Spacing.s4). */
object Spacing {
${dims("space")}
}

/** Corner radii: RoundedCornerShape(Radius.md). */
object Radius {
${dims("radius")}
}

/** Durations (ms) and easing curves: animateFloatAsState(target, Motion.spec(Motion.standard, Motion.move, reduced)). */
object Motion {
${durations.map(([n, v]) => `    const val ${n} = ${Math.round(v)}`).join("\n")}

${curves.map(([n, p]) => `    val ${n}: Easing = CubicBezierEasing(${p.map(float).join(", ")})`).join("\n")}

    /** A tween on a token; movement is instant when reduced (pass false for a fade, which may keep its time). */
    fun <T> spec(durationMillis: Int, easing: Easing, reduced: Boolean): FiniteAnimationSpec<T> =
        tween(durationMillis = if (reduced) 0 else durationMillis, easing = easing)
}

/** True when the user turned animations off (Settings > Accessibility > Remove animations). */
@Composable
fun rememberReducedMotion(): Boolean {
    val resolver = LocalContext.current.contentResolver
    return remember(resolver) { Settings.Global.getFloat(resolver, Settings.Global.ANIMATOR_DURATION_SCALE, 1f) == 0f }
}
`;
}

/** {file name: content} for the four Kotlin files, in package pkg. */
export function composeFiles(tokens, pkg = "ui.theme") {
  if (!/^[a-z_][\w]*(\.[a-z_][\w]*)*$/i.test(pkg)) throw new Error(`--package ${pkg} is not a Kotlin package name`);
  const rows = flatten(tokens);
  return {
    "Color.kt": colorKt(pkg, rows),
    "Type.kt": typeKt(pkg, rows),
    "Theme.kt": themeKt(pkg, rows),
    "Tokens.kt": tokensKt(pkg, rows, tokens),
  };
}
