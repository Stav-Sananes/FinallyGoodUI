// Token formats for React Native styling layers. Native views can't read var() in StyleSheet values,
// rem, em letter-spacing or unitless line-height, and React Native parses only sRGB colour notations,
// so every value here is a literal: hex / rgba colours, px sizes, line-height and letter-spacing in
// px per text step. Colours still switch with the theme through each layer's own mechanism.
import { flatten, groupTokens, parseDimension, parseDuration, parseEasing, textMetrics, fontLoad } from "./tokens.mjs";
import { parseColor, toHex } from "./contrast.mjs";
import { camel } from "./names.mjs";

const round = (n, places = 2) => Math.round(n * 10 ** places) / 10 ** places;
const COLOR_FN = /(?:oklch|oklab|rgba?|hsla?)\([^)]*\)|#[0-9a-f]{3,8}\b/gi;

/** Any CSS colour as "#rrggbb", or "rgba(r, g, b, a)" when translucent. */
export function nativeColor(css) {
  const c = parseColor(css);
  if (!c) throw new Error(`cannot convert colour ${css} to sRGB`);
  if (c.a >= 1) return toHex(c);
  const [r, g, b] = [c.r, c.g, c.b].map((x) => Math.round(x * 255));
  return `rgba(${r}, ${g}, ${b}, ${round(c.a, 3)})`;
}

/** "R G B" channels for rgb(var(--x) / <alpha-value>), or null for a translucent colour. */
function channels(css) {
  const c = parseColor(css);
  if (!c || c.a < 1) return null;
  return [c.r, c.g, c.b].map((x) => Math.round(x * 255)).join(" ");
}

const nativeShadow = (css) => css.replace(COLOR_FN, (m) => nativeColor(m));

/** Per text step: font size, and line-height / letter-spacing turned into px for that size. */
function textSteps(rows) {
  return rows.filter((r) => r.group === "text").map((r) => {
    const size = parseDimension(r.light)?.value;
    const metrics = Object.fromEntries(textMetrics(r.token).map((m) => [m.suffix, m.value]));
    const lh = Number(metrics["line-height"]);
    const ls = parseDimension(metrics["letter-spacing"] ?? "");
    return {
      name: r.name, size: `${size}px`,
      lineHeight: Number.isFinite(lh) ? `${round(lh * size, 1)}px` : null,
      letterSpacing: ls ? `${round(ls.unit === "em" ? ls.value * size : ls.value)}px` : null,
    };
  });
}

/** Font tokens React Native can use: a loaded face, by its first family name (register it with expo-font). */
const nativeFonts = (rows) => rows.filter((r) => r.group === "font" && fontLoad(r.token))
  .map((r) => ({ name: r.name, family: [].concat(r.token.$value)[0] }));

const pxGroup = (rows, group) => rows.filter((r) => r.group === group && parseDimension(r.light)).map((r) => ({ name: r.name, value: r.light }));

// ---------- Uniwind (Tailwind v4 bindings for React Native) ----------

/** What a native format leaves out, and where it lives instead. */
const skipped = (more = []) => `/* Not here: ${["letter-spacing tokens (tracking-*: em has no size on native; each text step carries its own)",
  "motion (--format rn-motion, for Reanimated)", "system font stacks (React Native uses the platform font)", ...more].join("; ")}. */`;

export function emitUniwind(tokens) {
  const rows = flatten(tokens);
  const colors = rows.filter((r) => r.group === "color");
  const theme = [];
  for (const t of textSteps(rows)) {
    theme.push(`--text-${t.name}: ${t.size};`);
    if (t.lineHeight) theme.push(`--text-${t.name}--line-height: ${t.lineHeight};`);
    if (t.letterSpacing) theme.push(`--text-${t.name}--letter-spacing: ${t.letterSpacing};`);
  }
  for (const f of nativeFonts(rows)) theme.push(`--font-${f.name}: "${f.family}";`);
  for (const s of pxGroup(rows, "space")) theme.push(`--spacing-${s.name}: ${s.value};`);
  for (const r of pxGroup(rows, "radius")) theme.push(`--radius-${r.name}: ${r.value};`);
  for (const r of rows.filter((x) => x.group === "shadow")) theme.push(`--shadow-${r.name}: ${nativeShadow(r.light)};`);
  const variant = (name, pick) => `    @variant ${name} {\n${colors.map((r) => `      ${r.varName}: ${nativeColor(pick(r))};`).join("\n")}\n    }`;
  return `/* generated by finally-good-ui emit-tokens.mjs (--format uniwind); edit the tokens, not this block.
   global.css, after @import 'tailwindcss'; @import 'uniwind';
   Colours switch with the theme (Uniwind follows the device unless Uniwind.setTheme('light' | 'dark') is called);
   the rest is the same in both themes. Uniwind also serves react-native-reusables and gluestack on Uniwind. */
${skipped()}
@theme {
${theme.map((d) => `  ${d}`).join("\n")}
}

@layer theme {
  :root {
${variant("light", (r) => r.light)}
${variant("dark", (r) => r.dark ?? r.light)}
  }
}
`;
}

// ---------- NativeWind v4 (Tailwind v3 config + CSS variables) ----------

export function emitNativewind(tokens) {
  const rows = flatten(tokens);
  const colors = rows.filter((r) => r.group === "color");
  const value = (css) => channels(css) ?? nativeColor(css);
  const decls = (pick) => colors.map((r) => `  ${r.varName}: ${value(pick(r))};`).join("\n");
  const configColor = (r) => (channels(r.light) && (r.dark == null || channels(r.dark))
    ? `rgb(var(${r.varName}) / <alpha-value>)` : `var(${r.varName})`);
  const obj = (entries) => `{ ${entries.map(([k, v]) => `${JSON.stringify(k)}: ${v}`).join(", ")} }`;
  const fontSize = textSteps(rows).map((t) => [t.name, `[${JSON.stringify(t.size)}, ${obj([
    ...(t.lineHeight ? [["lineHeight", JSON.stringify(t.lineHeight)]] : []),
    ...(t.letterSpacing ? [["letterSpacing", JSON.stringify(t.letterSpacing)]] : []),
  ])}]`]);
  const fonts = nativeFonts(rows).map((f) => [f.name, JSON.stringify([f.family])]);
  const extend = [
    ["colors", obj(colors.map((r) => [r.name, JSON.stringify(configColor(r))]))],
    ["fontSize", obj(fontSize)],
    ...(fonts.length ? [["fontFamily", obj(fonts)]] : []),
    ["spacing", obj(pxGroup(rows, "space").map((s) => [s.name, JSON.stringify(s.value)]))],
    ["borderRadius", obj(pxGroup(rows, "radius").map((r) => [r.name, JSON.stringify(r.value)]))],
  ];
  return `/* generated by finally-good-ui emit-tokens.mjs (--format nativewind); edit the tokens, not this output.
   NativeWind v4. Two parts: the CSS variables for global.css, and theme.extend for tailwind.config.js.
   Dark values apply when NativeWind's colour scheme is dark: it follows the device by default;
   colorScheme.set("light" | "dark" | "system") from "nativewind" overrides it. Opaque colours are
   "R G B" channels so opacity modifiers (bg-primary/90) work; translucent ones are whole rgba() values.
   react-native-reusables on NativeWind: replace the colours in its tailwind.config.js with these. */
${skipped(["shadows (NativeWind v4 maps shadow-* to each platform's own shadow props)"])}

/* ---- global.css (keep one set of @tailwind lines) ---- */
@tailwind base;
@tailwind components;
@tailwind utilities;

/* Outside @layer base: Tailwind 3 drops layered rules whose class (.dark) no source file mentions. */
:root {
${decls((r) => r.light)}
}

.dark:root {
${decls((r) => r.dark ?? r.light)}
}

/* ---- tailwind.config.js (merge theme.extend into the existing config) ---- */
module.exports = {
  darkMode: "class",
  content: ["./app/**/*.{js,jsx,ts,tsx}", "./components/**/*.{js,jsx,ts,tsx}"],
  presets: [require("nativewind/preset")],
  theme: {
    extend: {
${extend.map(([k, v]) => `      ${k}: ${v},`).join("\n")}
    },
  },
};
`;
}

// ---------- Reanimated 4 motion tokens ----------

export function emitRnMotion(tokens) {
  const durations = Object.fromEntries([...groupTokens(tokens?.duration)].map(([n, t]) => [n, parseDuration(t.$value)?.value]).filter(([, v]) => v != null));
  const easings = Object.fromEntries([...groupTokens(tokens?.easing)].map(([n, t]) => [n, parseEasing(t.$value)]).filter(([, v]) => v));
  const curves = (fn) => Object.entries(easings).map(([n, p]) => `  ${JSON.stringify(n)}: ${fn}(${p.join(", ")}),`).join("\n");
  return `// generated by finally-good-ui emit-tokens.mjs (--format rn-motion); edit the tokens, not this file.
// Motion tokens for React Native with Reanimated 4 (New Architecture): CSS transitions and animations
// take \`transition()\` / \`ease\`; withTiming takes \`timing()\`. Animate transform and opacity only.
import { cubicBezier, Easing, ReduceMotion } from "react-native-reanimated";

/** Durations in ms. */
export const duration = ${JSON.stringify(durations, null, 2)};

/** Easing curves for Reanimated CSS transitions and animations (transitionTimingFunction, animationTimingFunction). */
export const ease = {
${curves("cubicBezier")}
};

/** The same curves for withTiming. */
export const easing = {
${curves("Easing.bezier")}
};

const known = (map, kind, name) => {
  if (!Object.hasOwn(map, name)) throw new Error(\`unknown \${kind} token "\${name}"\`);
  return map[name];
};

/** withTiming(value, timing("standard", "enter")). Reanimated skips it when the device asks for reduced motion. */
export const timing = (durationName, easeName) => ({
  duration: known(duration, "duration", durationName),
  easing: known(easing, "easing", easeName),
  reduceMotion: ReduceMotion.System,
});

/**
 * Style for a Reanimated CSS transition: <Animated.View style={[styles.card, transition(["transform", "opacity"],
 * "standard", "move", { reduced })]} /> with reduced = useReducedMotion(). Under reduced motion movement is
 * instant and an opacity-only transition keeps its fade.
 */
export function transition(properties, durationName, easeName, { reduced = false } = {}) {
  const props = [].concat(properties);
  const fadeOnly = props.every((p) => p === "opacity");
  return {
    transitionProperty: props,
    transitionDuration: reduced && !fadeOnly ? 0 : known(duration, "duration", durationName),
    transitionTimingFunction: known(ease, "easing", easeName),
  };
}
`;
}

// ---------- Tamagui v3 (createTamagui over @tamagui/config/v6) ----------

/** Tamagui's own theme keys, which its components read, filled from our roles. */
const TAMAGUI_KEYS = {
  background: "background", "background-hover": "accent", "background-press": "muted", "background-focus": "accent",
  "background-active": "muted", "border-color": "border", "border-color-hover": "input", "border-color-press": "input",
  "border-color-focus": "ring", color: "foreground", "color-hover": "foreground", "color-press": "foreground",
  "color-focus": "foreground", "placeholder-color": "muted-foreground", "outline-color": "ring",
  "accent-background": "primary", "accent-color": "primary-foreground",
};

const objectLiteral = (entries, indent) => `{\n${entries.map(([k, v]) => `${indent}  ${JSON.stringify(k)}: ${v},`).join("\n")}\n${indent}}`;

function themeColors(rows, pick) {
  const ours = Object.fromEntries(rows.filter((r) => r.group === "color").map((r) => [r.name, nativeColor(pick(r))]));
  const mapped = Object.entries(TAMAGUI_KEYS).filter(([, role]) => ours[role]).map(([key, role]) => [key, ours[role]]);
  return [...mapped, ...Object.entries(ours).filter(([name]) => !(name in TAMAGUI_KEYS))];
}

// Tamagui refuses token names that are CSS-wide keywords (they would always resolve as the keyword).
const TAMAGUI_RESERVED = new Set(["inherit", "initial", "unset", "revert", "none", "auto", "transparent", "currentcolor"]);

export function emitTamagui(tokens) {
  const rows = flatten(tokens);
  const numbers = (group) => pxGroup(rows, group).filter((t) => !TAMAGUI_RESERVED.has(t.name.toLowerCase()))
    .map((t) => [t.name, String(parseDimension(t.value).value)]);
  const theme = (pick) => objectLiteral(themeColors(rows, pick).map(([k, v]) => [k, JSON.stringify(v)]), "    ");
  return `// generated by finally-good-ui emit-tokens.mjs (--format tamagui); edit the tokens, not this file.
// tamagui.config.ts for Tamagui 3: the v6 defaults with our space and radius tokens and our colours in the
// light and dark themes, under Tamagui's own keys (background, border-color, color…) and our role names
// (primary, card, muted-foreground…). Sub-themes (light_white, dark_brand…) keep Tamagui's values.
// Tokens named after CSS keywords (radius "none") are left out: Tamagui rejects them; use radius "0".
// Tamagui 1.x / 2.x use camelCase theme keys: rename background-hover to backgroundHover and so on.
import { defaultConfig } from "@tamagui/config/v6";
import { createTamagui, createTokens } from "tamagui";

const tokens = createTokens({
  ...defaultConfig.tokens,
  space: { ...defaultConfig.tokens.space, ...${objectLiteral(numbers("space"), "  ")} },
  radius: { ...defaultConfig.tokens.radius, ...${objectLiteral(numbers("radius"), "  ")} },
});

export const config = createTamagui({
  ...defaultConfig,
  tokens,
  themes: {
    ...defaultConfig.themes,
    light: { ...defaultConfig.themes.light, ...${theme((r) => r.light)} },
    dark: { ...defaultConfig.themes.dark, ...${theme((r) => r.dark ?? r.light)} },
  },
});

type AppConfig = typeof config;
declare module "tamagui" {
  interface TamaguiCustomConfig extends AppConfig {}
}
export default config;
`;
}

// ---------- Unistyles v3 (StyleSheet.configure) ----------


export function emitUnistyles(tokens) {
  const rows = flatten(tokens);
  const durations = [...groupTokens(tokens?.duration)].map(([n, t]) => [camel(n), String(parseDuration(t.$value)?.value)]);
  const text = textSteps(rows).map((t) => [t.name, `{ fontSize: ${parseFloat(t.size)}${t.lineHeight ? `, lineHeight: ${parseFloat(t.lineHeight)}` : ""}${t.letterSpacing ? `, letterSpacing: ${parseFloat(t.letterSpacing)}` : ""} }`]);
  const shared = [
    ["space", objectLiteral(pxGroup(rows, "space").map((t) => [t.name, String(parseFloat(t.value))]), "  ")],
    ["radius", objectLiteral(pxGroup(rows, "radius").map((t) => [t.name, String(parseFloat(t.value))]), "  ")],
    ["text", objectLiteral(text, "  ")],
    ["duration", objectLiteral(durations, "  ")],
  ];
  const theme = (pick) => objectLiteral([
    ["colors", objectLiteral(rows.filter((r) => r.group === "color").map((r) => [camel(r.name), JSON.stringify(nativeColor(pick(r)))]), "  ")],
    ["shadow", objectLiteral(rows.filter((r) => r.group === "shadow").map((r) => [r.name, JSON.stringify(nativeShadow(pick(r)))]), "  ")],
    ...shared.map(([k]) => [k, k]),
  ], "");
  return `// generated by finally-good-ui emit-tokens.mjs (--format unistyles); edit the tokens, not this file.
// unistyles.ts for Unistyles 3 (New Architecture): import it once, before any StyleSheet.create
// (top of index.ts or app/_layout.tsx). The theme follows the device (adaptiveThemes); call
// UnistylesRuntime.setAdaptiveThemes(false) and UnistylesRuntime.setTheme("dark") for a manual toggle.
// Use: StyleSheet.create((theme) => ({ card: { backgroundColor: theme.colors.card, padding: theme.space[4],
// borderRadius: theme.radius.md, boxShadow: theme.shadow.sm, ...theme.text.base } })).
import { StyleSheet } from "react-native-unistyles";

${shared.map(([k, v]) => `const ${k} = ${v};`).join("\n")}

const lightTheme = ${theme((r) => r.light)};

const darkTheme = ${theme((r) => r.dark ?? r.light)};

type AppThemes = { light: typeof lightTheme; dark: typeof darkTheme };
declare module "react-native-unistyles" {
  export interface UnistylesThemes extends AppThemes {}
}

StyleSheet.configure({
  settings: { adaptiveThemes: true },
  themes: { light: lightTheme, dark: darkTheme },
});
`;
}
