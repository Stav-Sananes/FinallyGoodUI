// Generates chart-theme.js: chart colours for canvas renderers (ECharts, Chart.js, AG Charts, uPlot),
// which can't read CSS variables. At runtime the module reads the live variables (so a theme switch or
// override wins) and resolves any CSS colour to sRGB through a 1x1 canvas; without a DOM it falls
// back to the tokens' light values, already resolved here.
import { flatten, groupTokens, parseDuration } from "./tokens.mjs";
import { toHex } from "./contrast.mjs";

const ROLES = { text: "foreground", mutedText: "muted-foreground", grid: "border", surface: "card", background: "background" };

function fallbacks(tokens) {
  const colors = Object.fromEntries(flatten(tokens).filter((r) => r.group === "color").map((r) => [r.name, toHex(r.light)]));
  const series = Object.keys(colors).filter((n) => /^chart-\d+$/.test(n))
    .sort((a, b) => Number(a.slice(6)) - Number(b.slice(6)));
  if (!series.length) throw new Error("the token set has no chart colours (color.chart-1, chart-2, …)");
  const font = flatten(tokens).find((r) => r.group === "font" && r.name === "sans")?.light ?? "system-ui, sans-serif";
  const duration = parseDuration([...groupTokens(tokens?.duration)].find(([n]) => n === "standard")?.[1].$value)?.value ?? 250;
  return {
    series: series.map((n) => ({ name: n, fallback: colors[n] })),
    roles: Object.fromEntries(Object.entries(ROLES).map(([role, name]) => [role, { name, fallback: colors[name] ?? null }])),
    font, duration,
  };
}

export function emitChartTheme(tokens) {
  const f = fallbacks(tokens);
  return `// generated by finally-good-ui emit-tokens.mjs (--format chart-theme); edit the tokens, not this file.
// Chart colours for canvas renderers (ECharts, Chart.js, AG Charts, uPlot), which can't read CSS variables.
// SVG chart libraries (Recharts, visx, Plot, Unovis, LayerChart) don't need this: use var(--color-chart-N).
// Call after the CSS has loaded and again from onThemeChange(): values come from the live variables.
const SERIES = ${JSON.stringify(f.series)};
const ROLES = ${JSON.stringify(f.roles)};
const FALLBACK_FONT = ${JSON.stringify(f.font)};
const FALLBACK_DURATION = ${f.duration};

const hasDom = () => typeof document !== "undefined" && typeof getComputedStyle === "function";
const cssVar = (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim();
const liveColor = (name) => cssVar(\`--color-\${name}\`) || cssVar(\`--\${name}\`); // ours, then shadcn's names

let probe;
/** Any CSS colour (oklch, color-mix, var-resolved…) -> "#rrggbb" or "rgba(…)", via a 1x1 canvas; null if invalid. */
function toCanvasColor(css) {
  if (!css || !hasDom()) return null;
  probe ||= Object.assign(document.createElement("canvas"), { width: 1, height: 1 }).getContext("2d", { willReadFrequently: true });
  probe.fillStyle = "#010203";
  probe.fillStyle = css;
  if (probe.fillStyle === "#010203" && !/^#010203$/i.test(css)) return null;
  probe.clearRect(0, 0, 1, 1);
  probe.fillRect(0, 0, 1, 1);
  const [r, g, b, a] = probe.getImageData(0, 0, 1, 1).data;
  const hex = "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");
  return a === 255 ? hex : \`rgba(\${r}, \${g}, \${b}, \${(a / 255).toFixed(3)})\`;
}
const color = ({ name, fallback }) => (hasDom() && toCanvasColor(liveColor(name))) || fallback;

/** Durations for chart animation: the live --duration-standard, 0 under reduced motion. */
function animationMs() {
  if (!hasDom()) return FALLBACK_DURATION;
  if (typeof matchMedia === "function" && matchMedia("(prefers-reduced-motion: reduce)").matches) return 0;
  const live = cssVar("--duration-standard"), n = parseFloat(live);
  return Number.isFinite(n) ? (/ms$/.test(live) ? n : /s$/.test(live) ? n * 1000 : n) : FALLBACK_DURATION;
}

/** Resolved colours: { series: [...], text, mutedText, grid, surface, background, font, duration }. */
export function chartColors() {
  const roles = Object.fromEntries(Object.entries(ROLES).map(([role, ref]) => [role, color(ref)]));
  const font = (hasDom() && cssVar("--font-sans")) || FALLBACK_FONT;
  return { series: SERIES.map(color), ...roles, font, duration: animationMs() };
}

/** ECharts theme: echarts.registerTheme("fgu", echartsTheme()); echarts.init(el, "fgu"). */
export function echartsTheme() {
  const c = chartColors();
  const axis = {
    axisLine: { lineStyle: { color: c.grid } }, axisTick: { lineStyle: { color: c.grid } },
    axisLabel: { color: c.mutedText }, splitLine: { lineStyle: { color: c.grid } },
  };
  return {
    color: c.series, backgroundColor: "transparent",
    textStyle: { color: c.text, fontFamily: c.font },
    title: { textStyle: { color: c.text }, subtextStyle: { color: c.mutedText } },
    legend: { textStyle: { color: c.mutedText } },
    tooltip: { backgroundColor: c.surface, borderColor: c.grid, textStyle: { color: c.text } },
    categoryAxis: axis, valueAxis: axis, timeAxis: axis, logAxis: axis,
    animationDuration: c.duration, animationDurationUpdate: c.duration,
  };
}

/** Chart.js: sets Chart.defaults from the tokens and returns the series colours for your datasets. */
export function applyChartJsTheme(Chart) {
  const c = chartColors();
  const d = Chart.defaults;
  d.color = c.mutedText;
  d.borderColor = c.grid;
  d.font.family = c.font;
  d.plugins.tooltip.backgroundColor = c.surface;
  d.plugins.tooltip.titleColor = c.text;
  d.plugins.tooltip.bodyColor = c.text;
  d.animation.duration = c.duration;
  return c.series;
}

/** Calls cb when the colour scheme changes (OS setting, or a class/attribute toggle on <html>). Returns unsubscribe. */
export function onThemeChange(cb) {
  if (!hasDom()) return () => {};
  const mq = typeof matchMedia === "function" ? matchMedia("(prefers-color-scheme: dark)") : null;
  mq?.addEventListener("change", cb);
  const mo = new MutationObserver(cb);
  mo.observe(document.documentElement, { attributes: true, attributeFilter: ["class", "style", "data-theme", "data-mode", "data-color-scheme"] });
  return () => { mq?.removeEventListener("change", cb); mo.disconnect(); };
}
`;
}
