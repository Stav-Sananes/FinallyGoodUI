import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { run, tmp, SR } from "./_h.mjs";
import { detectStack } from "../detect-stack.mjs";
import { kotlinColor, kotlinName } from "../lib/compose.mjs";

// An Android app gets the four Kotlin files Material Theme Builder would export, filled from our
// tokens. Checked with AGP 8.13, Kotlin 2.4 and the Compose BOM 2025.10 (Compose 1.9): the files compile with a
// screen that uses AppTheme, the extended colours, Spacing, Radius and Motion, and a JVM test reads
// the values back.
const DEF = join(SR, "tokens", "default.tokens.resolver.json");
function exportTo(...more) {
  const out = join(tmp(), "theme");
  const r = run("emit-tokens.mjs", ["--in", DEF, "--format", "compose", "--out-dir", out, "--package", "com.acme.app.ui.theme", ...more]);
  assert.equal(r.code, 0, r.stderr);
  return { out, r, read: (f) => readFileSync(join(out, f), "utf8") };
}

test("Color.kt: every role as a Light and a Dark ARGB constant", () => {
  const { r, read } = exportTo();
  assert.deepEqual(r.json.written, ["Color.kt", "Type.kt", "Theme.kt", "Tokens.kt"]);
  const kt = read("Color.kt");
  assert.match(kt, /^\/\/ generated by finally-good-ui[^\n]*\npackage com\.acme\.app\.ui\.theme\n/);
  assert.match(kt, /val PrimaryLight = Color\(0xFF345FB2\)/);
  assert.match(kt, /val PrimaryDark = Color\(0xFF7BA4F0\)/);
  assert.match(kt, /val OverlayLight = Color\(0x7316181E\)/);
  assert.match(kt, /val Chart8Dark = Color\(0xFF/);
});

test("Theme.kt: ColorScheme slots from our roles, extended colours, shapes, AppTheme following the system", () => {
  const kt = exportTo().read("Theme.kt");
  assert.match(kt, /private val LightColors = lightColorScheme\(\n {4}primary = PrimaryLight,/);
  assert.match(kt, /background = BackgroundLight,\n {4}onBackground = ForegroundLight,/);
  assert.match(kt, /outlineVariant = BorderDark,/);
  assert.match(kt, /surfaceTint = Color\.Transparent,/);
  assert.match(kt, /data class ExtendedColors\([\s\S]*val success: Color,[\s\S]*val chart8: Color,/);
  assert.doesNotMatch(kt.split("data class ExtendedColors")[1].split(")")[0], /val primary:/);
  assert.match(kt, /medium = RoundedCornerShape\(8\.dp\),/);
  assert.match(kt, /fun AppTheme\(darkTheme: Boolean = isSystemInDarkTheme\(\), content: @Composable \(\) -> Unit\)/);
});

test("Type.kt and Tokens.kt: sp metrics per step, dp spacing, ms durations, easing curves, reduced motion", () => {
  const { read } = exportTo();
  assert.match(read("Type.kt"), /bodyMedium = TextStyle\(fontSize = 16\.sp, lineHeight = 24\.sp, letterSpacing = 0\.sp\),/);
  assert.match(read("Type.kt"), /headlineMedium = TextStyle\(fontSize = 24\.sp, lineHeight = 31\.2\.sp, letterSpacing = -0\.24\.sp\),/);
  const t = read("Tokens.kt");
  assert.match(t, /val s4 = 16\.dp/);
  assert.match(t, /const val standard = 250/);
  assert.match(t, /val enterEmphasized: Easing = CubicBezierEasing\(0\.05f, 0\.7f, 0\.1f, 1f\)/);
  assert.match(t, /tween\(durationMillis = if \(reduced\) 0 else durationMillis, easing = easing\)/);
  assert.match(t, /Settings\.Global\.ANIMATOR_DURATION_SCALE, 1f\) == 0f/);
});

test("compose needs --out-dir and a valid package", () => {
  assert.equal(run("emit-tokens.mjs", ["--in", DEF, "--format", "compose"]).code, 2);
  const bad = run("emit-tokens.mjs", ["--in", DEF, "--format", "compose", "--out-dir", tmp(), "--package", "com.acme-app"]);
  assert.equal(bad.code, 2);
  assert.match(bad.stderr, /not a Kotlin package name/);
});

test("detect: a Gradle build with Compose on is a Compose app; a plain Android or JVM build is not", () => {
  const app = tmp();
  writeFileSync(join(app, "settings.gradle.kts"), 'include(":app")\n');
  mkdirSync(join(app, "app"));
  writeFileSync(join(app, "app", "build.gradle.kts"), "android {\n  buildFeatures { compose = true }\n}\n");
  const p = detectStack(app);
  assert.equal(p.framework, "compose");
  assert.equal(p.viewTransitions, null);
  const plain = tmp();
  writeFileSync(join(plain, "settings.gradle.kts"), "");
  writeFileSync(join(plain, "build.gradle.kts"), 'plugins { kotlin("jvm") }\n');
  assert.notEqual(detectStack(plain).framework, "compose");
  assert.equal(kotlinName("2xl"), "s2xl");
  assert.equal(kotlinColor("#000000"), "Color(0xFF000000)");
});
